# Regenerates the generated parts of the documentation from the source code:
#
#   docs/reference/BACKEND_CODE_REFERENCE.md  - every backend class: purpose (from its
#                                               Javadoc), role, table, endpoints, methods
#   docs/reference/DATABASE_MIGRATIONS.md     - every Flyway migration with its header
#   docs/appendix/*.md                        - the full source code, one file per area
#
# Run from the repository root:   powershell -ExecutionPolicy Bypass -File docs/generate-reference.ps1
# The hand-written guide is docs/PROJECT_DOCUMENTATION.md; it is not touched.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
$utf8 = New-Object System.Text.UTF8Encoding($false)
New-Item -ItemType Directory -Force docs/reference, docs/appendix | Out-Null

function Read-Text($path) { [IO.File]::ReadAllText((Resolve-Path $path), [Text.Encoding]::UTF8) }
function Rel($path) { (Resolve-Path -Relative $path).TrimStart('.', '\', '/').Replace('\', '/') }

# Javadoc -> readable Markdown text.
function Clean-Javadoc([string]$raw) {
    $lines = $raw -split "`r?`n" | ForEach-Object { $_ -replace '^\s*\*\s?', '' }
    $t = ($lines -join "`n").Trim()
    $t = [regex]::Replace($t, '(?s)<pre>(.*?)</pre>', { param($m) "`n``````text`n" + $m.Groups[1].Value.Trim("`n") + "`n``````n" })
    $t = [regex]::Replace($t, '\{@(?:code|literal)\s+([^{}]*)\}', '`$1`')
    $t = [regex]::Replace($t, '\{@link(?:plain)?\s+([^{}\s]+)(?:\s+([^{}]+))?\}', { param($m) if ($m.Groups[2].Success) { $m.Groups[2].Value } else { '`' + ($m.Groups[1].Value -replace '#', '.') + '`' } })
    $t = $t -replace '<p>', "`n`n" -replace '</?(ul|ol)>', "`n" -replace '<li>', "`n- " -replace '</li>', '' -replace '</?(em|i)>', '*' -replace '</?(strong|b)>', '**' -replace '<[^>]+>', ''
    $t = $t -replace '&lt;', '<' -replace '&gt;', '>' -replace '&amp;', '&'
    $t = ($t -split "`n" | ForEach-Object { $_.TrimEnd() }) -join "`n"
    return ([regex]::Replace($t, "\n{3,}", "`n`n")).Trim()
}

function Role-Of([string]$c, [string]$kind, [string]$name) {
    if ($c -match '@RestController') { return 'REST controller' }
    if ($c -match '@ControllerAdvice|@RestControllerAdvice') { return 'Error handler' }
    if ($c -match '@Entity') { return 'Database entity' }
    if ($kind -eq 'interface' -and $c -match 'extends\s+JpaRepository') { return 'Repository (data access)' }
    if ($c -match '@Configuration') { return 'Spring configuration' }
    if ($c -match '@Service') { return 'Service (business logic)' }
    if ($c -match '@Component') { return 'Spring component' }
    if ($c -match '@ConfigurationProperties') { return 'Configuration properties' }
    if ($kind -eq 'record') { return 'Data record (DTO)' }
    if ($kind -eq 'enum') { return 'Enumeration' }
    if ($name -match 'Exception$') { return 'Exception type' }
    if ($kind -eq 'interface') { return 'Interface' }
    return 'Class'
}

# ── Backend reference ────────────────────────────────────────────────────────
$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('# Backend code reference')
[void]$out.AppendLine()
[void]$out.AppendLine('*Generated by `docs/generate-reference.ps1` from the source code; do not edit by hand.*')
[void]$out.AppendLine('Each entry gives the file, what kind of class it is, its purpose (taken from its own documentation comment), and its HTTP endpoints or public methods. The explanation of how these parts work together is in [`../PROJECT_DOCUMENTATION.md`](../PROJECT_DOCUMENTATION.md).')
[void]$out.AppendLine()

$javaFiles = Get-ChildItem src/main/java -Recurse -Filter *.java | Sort-Object FullName
$byPackage = $javaFiles | Group-Object { (Rel $_.DirectoryName) -replace '^src/main/java/com/mailflow/?', '' }
[void]$out.AppendLine('## Packages')
[void]$out.AppendLine()
foreach ($g in $byPackage) {
    $pkg = if ($g.Name) { $g.Name.Replace('/', '.') } else { '(root)' }
    [void]$out.AppendLine("- [``com.mailflow.$pkg``](#$(('com.mailflow.' + $pkg).Replace('.', '').ToLower())) ($($g.Count) files)")
}
[void]$out.AppendLine()

foreach ($g in $byPackage) {
    $pkg = if ($g.Name) { $g.Name.Replace('/', '.') } else { '(root)' }
    [void]$out.AppendLine("## com.mailflow.$pkg")
    [void]$out.AppendLine()
    foreach ($f in $g.Group) {
        $c = Read-Text $f.FullName
        $decl = [regex]::Match($c, '(?m)^public\s+(?:final\s+|abstract\s+|sealed\s+)*(class|interface|record|enum)\s+(\w+)')
        if (-not $decl.Success) { continue }
        $kind = $decl.Groups[1].Value; $name = $decl.Groups[2].Value
        $head = $c.Substring(0, $decl.Index)
        $docs = [regex]::Matches($head, '(?s)/\*\*(.*?)\*/')
        $doc = if ($docs.Count -gt 0) { Clean-Javadoc $docs[$docs.Count - 1].Groups[1].Value } else { '' }
        $role = Role-Of $c $kind $name
        [void]$out.AppendLine("### $name")
        [void]$out.AppendLine()
        $meta = "``$(Rel $f.FullName)`` - $role"
        $tbl = [regex]::Match($c, '@Table\(\s*name\s*=\s*"([^"]+)"'); if ($tbl.Success) { $meta += " - table ``$($tbl.Groups[1].Value)``" }
        if ($c -match '@org\.hibernate\.annotations\.TenantId|@TenantId') { $meta += ' - company-scoped (`@TenantId`)' }
        [void]$out.AppendLine($meta)
        [void]$out.AppendLine()
        if ($doc) { [void]$out.AppendLine($doc); [void]$out.AppendLine() }

        if ($role -eq 'REST controller') {
            $base = ([regex]::Match($c, '@RequestMapping\(\s*(?:value\s*=\s*|path\s*=\s*)?"([^"]*)"')).Groups[1].Value
            $classAuth = ([regex]::Match($head + $c.Substring($decl.Index, [Math]::Min(200, $c.Length - $decl.Index)), '@PreAuthorize\("([^"]+)"\)\s*(?:@\w+[^\n]*\s*)*public\s+class')).Groups[1].Value
            $eps = [regex]::Matches($c, '(?s)@(Get|Post|Put|Patch|Delete)Mapping(?:\(([^)]*)\))?(.*?)public\s+[^=;(){}]+?\s+(\w+)\s*\(')
            if ($eps.Count -gt 0) {
                [void]$out.AppendLine('| Method | Path | Handler | Summary | Access |')
                [void]$out.AppendLine('|---|---|---|---|---|')
                foreach ($e in $eps) {
                    $args = $e.Groups[2].Value
                    $p = ([regex]::Match($args, '(?:^|value\s*=\s*|path\s*=\s*)"([^"]*)"')).Groups[1].Value
                    $between = $e.Groups[3].Value
                    $sum = ([regex]::Match($between, 'summary\s*=\s*"([^"]+)"')).Groups[1].Value
                    $auth = ([regex]::Match($between, '@PreAuthorize\("([^"]+)"\)')).Groups[1].Value
                    if (-not $auth) { $auth = $classAuth }
                    if (-not $auth) { $auth = 'see SecurityConfig' }
                    [void]$out.AppendLine("| $($e.Groups[1].Value.ToUpper()) | ``$base$p`` | ``$($e.Groups[4].Value)`` | $sum | ``$($auth.Replace('|','\|'))`` |")
                }
                [void]$out.AppendLine()
            }
        } else {
            $methods = [regex]::Matches($c, '(?m)^    (?:public|protected)\s+(?:static\s+)?(?:final\s+)?(?:<[^>]+>\s+)?([\w<>?,.\[\] ]+?)\s+(\w+)\s*\(([^)]*)\)')
            $sigs = $methods | Where-Object { $_.Groups[2].Value -ne $name } | ForEach-Object {
                $params = $_.Groups[3].Value -replace '@\w+(\([^)]*\))?\s*', ''
                $params = ($params -replace '\s+', ' ').Trim()
                '`' + $_.Groups[2].Value + '(' + $params + ')`'
            } | Select-Object -Unique
            if ($kind -eq 'interface' -and $role -like 'Repository*') {
                $qm = [regex]::Matches($c, '(?m)^\s{4}(?:[\w<>?,.\[\] ]+?)\s+([a-z]\w*)\s*\(') | ForEach-Object { "``$($_.Groups[1].Value)``" } | Select-Object -Unique
                if ($qm) { [void]$out.AppendLine('Queries: ' + ($qm -join ', ')); [void]$out.AppendLine() }
            } elseif ($kind -eq 'record') {
                $comp = ([regex]::Match($c, "(?s)record\s+$name\s*\((.*?)\)\s*(\{|implements)")).Groups[1].Value
                $fields = [regex]::Matches(($comp -replace '@\w+(\([^)]*\))?', ''), '([\w<>?,.\[\] ]+?)\s+(\w+)\s*(,|$)') | ForEach-Object { "``$($_.Groups[2].Value)``" }
                if ($fields) { [void]$out.AppendLine('Fields: ' + ($fields -join ', ')); [void]$out.AppendLine() }
            } elseif ($sigs) {
                [void]$out.AppendLine('Public methods: ' + ($sigs -join ', '))
                [void]$out.AppendLine()
            }
        }
    }
}
[IO.File]::WriteAllText("$root/docs/reference/BACKEND_CODE_REFERENCE.md", $out.ToString(), $utf8)

# ── Migrations ───────────────────────────────────────────────────────────────
$m = New-Object System.Text.StringBuilder
[void]$m.AppendLine('# Database migrations')
[void]$m.AppendLine()
[void]$m.AppendLine('*Generated by `docs/generate-reference.ps1`.* Flyway applies these in order on start-up; a migration is never edited after it has been applied, a new one is added instead.')
[void]$m.AppendLine()
foreach ($f in Get-ChildItem src/main/resources/db/migration -Filter *.sql | Sort-Object { [int](($_.Name -replace '^V(\d+)__.*', '$1')) }) {
    $sql = Read-Text $f.FullName
    $comment = ($sql -split "`r?`n" | Where-Object { $_ -match '^\s*--' } | Select-Object -First 14 | ForEach-Object { ($_ -replace '^\s*--\s?', '') -replace '^=+$', '' } | Where-Object { $_.Trim() -ne '' }) -join "`n"
    $tables = [regex]::Matches($sql, '(?i)CREATE TABLE\s+(?:IF NOT EXISTS\s+)?(\w+)') | ForEach-Object { "``$($_.Groups[1].Value)``" } | Select-Object -Unique
    [void]$m.AppendLine("## $($f.Name)")
    [void]$m.AppendLine()
    if ($comment) { [void]$m.AppendLine($comment); [void]$m.AppendLine() }
    if ($tables) { [void]$m.AppendLine('Creates: ' + ($tables -join ', ')); [void]$m.AppendLine() }
}
[IO.File]::WriteAllText("$root/docs/reference/DATABASE_MIGRATIONS.md", $m.ToString(), $utf8)

# ── Full-source appendices ───────────────────────────────────────────────────
function Write-Appendix($file, $title, $intro, $paths) {
    $a = New-Object System.Text.StringBuilder
    [void]$a.AppendLine("# $title"); [void]$a.AppendLine()
    [void]$a.AppendLine("*Generated by ``docs/generate-reference.ps1``.* $intro"); [void]$a.AppendLine()
    $all = foreach ($p in $paths) { if (Test-Path $p -PathType Container) { Get-ChildItem $p -Recurse -File -Include *.java, *.ts, *.tsx, *.sql, *.yml, *.yaml, *.css, *.json, *.js, *.conf | Where-Object { $_.FullName -notmatch 'node_modules|\\dist\\' } } elseif (Test-Path $p) { Get-Item $p } }
    $all = $all | Sort-Object FullName -Unique
    [void]$a.AppendLine('## Files'); [void]$a.AppendLine()
    foreach ($f in $all) { $r = Rel $f.FullName; [void]$a.AppendLine("- [$r](#$(($r -replace '[^A-Za-z0-9 -]', '').ToLower().Replace(' ', '-')))") }
    [void]$a.AppendLine()
    foreach ($f in $all) {
        $r = Rel $f.FullName
        $lang = switch -regex ($f.Extension) { '\.java' { 'java' } '\.tsx?' { 'tsx' } '\.sql' { 'sql' } '\.ya?ml' { 'yaml' } '\.css' { 'css' } '\.json' { 'json' } '\.js' { 'js' } default { 'text' } }
        if ($f.Name -eq 'Dockerfile') { $lang = 'dockerfile' } elseif ($f.Name -eq 'nginx.conf') { $lang = 'nginx' }
        [void]$a.AppendLine("## $r"); [void]$a.AppendLine()
        [void]$a.AppendLine('````' + $lang); [void]$a.AppendLine((Read-Text $f.FullName).TrimEnd()); [void]$a.AppendLine('````'); [void]$a.AppendLine()
    }
    [IO.File]::WriteAllText("$root/docs/appendix/$file", $a.ToString(), $utf8)
}
